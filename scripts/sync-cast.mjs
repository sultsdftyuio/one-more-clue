// Copies the case casts from art/out/cast into the app and writes src/lib/cast-art.ts.
// Run after `python art/cast.py`:  npm run art:cast
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const from = join(root, "art", "out", "cast", "webp");
const to = join(root, "src", "assets", "art", "cast");
const MOODS = ["idle", "nervous", "smug", "shocked", "cracked"];

if (!existsSync(from)) {
  console.error("No art/out/cast folder. Render the casts first: python art/cast.py");
  process.exit(1);
}
mkdirSync(to, { recursive: true });
const files = readdirSync(from).filter((f) => f.endsWith(".webp"));
for (const f of files) copyFileSync(join(from, f), join(to, f));

const keys = [...new Set(files.map((f) => f.replace(/-(idle|nervous|smug|shocked|cracked)\.webp$/, "")))].sort();
for (const key of keys) {
  const missing = MOODS.filter((m) => !files.includes(`${key}-${m}.webp`));
  if (missing.length) throw new Error(`${key} is missing ${missing.join(", ")}`);
}
const name = (key, mood) => `${key.replace(/-(\w)/g, (_, c) => c.toUpperCase())}${mood[0].toUpperCase()}${mood.slice(1)}`;
const lines = [
  "// Generated by scripts/sync-cast.mjs from art/cast.py. Don't edit by hand.",
  'import type { StaticImageData } from "next/image";',
  "",
  ...keys.flatMap((key) => MOODS.map((m) => `import ${name(key, m)} from "@/assets/art/cast/${key}-${m}.webp";`)),
  "",
  "/** How a suspect looks right now: resting, rattled, pleased with themselves, caught out, or giving it up. */",
  `export type Mood = ${MOODS.map((m) => `"${m}"`).join(" | ")};`,
  "",
  "/** Every case character's own drawing, in every mood, by their `look` key. */",
  "export const castArt: Record<string, Record<Mood, StaticImageData>> = {",
  ...keys.map((key) => `  "${key}": { ${MOODS.map((m) => `${m}: ${name(key, m)}`).join(", ")} },`),
  "};",
  "",
];
writeFileSync(join(root, "src", "lib", "cast-art.ts"), lines.join("\n"));
console.log(`Synced ${files.length} images for ${keys.length} characters.`);
